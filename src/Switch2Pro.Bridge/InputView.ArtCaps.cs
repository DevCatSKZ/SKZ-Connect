    private static readonly Dictionary<string, string> ArtCapMirror = new()
    {
        ["R"] = "L", ["ZR"] = "ZL", ["RB"] = "LB", ["RT"] = "LT", ["R1"] = "L1", ["R2"] = "L2",
    };

    private static GraphicsPath? ArtCapPath(string art, string label)
    {
        if (!ArtCaps.TryGetValue(art, out var caps)) return null;
        var mirror = false;
        if (!caps.TryGetValue(label, out var data))
        {
            if (!ArtCapMirror.TryGetValue(label, out var source) || !caps.TryGetValue(source, out data)) return null;
            mirror = true;
        }
        var points = new PointF[data.Length / 2];
        for (var i = 0; i < points.Length; i++)
        {
            var x = mirror ? 1491 - data[2 * i] : data[2 * i];
            points[i] = new PointF(
                ArtworkCanvas.X + x / 1491f * ArtworkCanvas.Width,
                ArtworkCanvas.Y + data[2 * i + 1] / 1055f * ArtworkCanvas.Height);
        }
        var path = new GraphicsPath();
        path.AddClosedCurve(points, 0.15f);
        return path;
    }
